function scope_checks_summary()
% SCOPE_CHECKS_SUMMARY  How far do the shares of members move when the membership test also
% rejects invading single toggles? Prints the 11 settings at generation 500 and the four
% architectures at generation 1, and the generation-1 share meeting the cooperation condition
% (C1) once silent and still-moving clone states are set aside.
%
% Produces : the toggle shifts (Methods, "Success, share of members and statistics"; SI S2.3,
%            "Scope: mutations and wirings outside the test"; Table S2); the (C1) shares (SI S2.3,
%            "Most random wirings that cooperate with their clone do not retaliate"); the
%            generation-1 member counts that tableS3_failed_and_gen1_rows reads (Table S3)
% Inputs   : publication/scope_checks/toggle_gen500_<tag>.mat (11 files; scope_checks_gen500)
%              and gen1_toggle_silent.mat (scope_checks_gen1)
%            publication/gen500_c1_c2_split.mat (cooperation_condition_shares_gen500) and
%              group_two_level/group_fission_analysis_N1000.mat (group_selection_arms):
%              the stored member counts per replicate and success, for the checks
%            publication/css_c1_c2_split.mat (cooperation_condition_shares; the stored generation-1
%              (C1) shares, for the check)
%            publication/share_of_members_checks_11settings.mat (share_of_members_vs_success; the stored
%              correlation over the 11 settings, for the check)
% Outputs  : publication/scope_checks/scope_checks_report.txt   (the lines this run prints)
% Run      : scope_checks_summary   (about 2 min)
% Seed     : none (no random draws)
%
% CONTROL lines compare counts, success and the correlation with the stored values (PASS or FAIL);
% the run stops unless the generation-1 (C1) shares equal the stored ones (44.45 / 42.36 / 44.35 /
% 42.11%).

    pub = fullfile(grn_data_file('publication'));
    out = fullfile(pub, 'scope_checks');
    fid = fopen(fullfile(out, 'scope_checks_report.txt'), 'w');
    cleaner = onCleanup(@() fclose(fid));
    p = @(varargin) both(fid, varargin{:});

    p('SCOPE CHECKS, generated by analysis/s2_share_of_members/scope_checks_summary.m\n\n');
    V1 = exp1_gen500(pub, out, p);
    V1b = exp1_gen1(out, p);
    exp1_shifts(V1, V1b, p);
    exp2(pub, out, p);
end


% =========================================================================
function V = exp1_gen500(pub, out, p)
% Generation 500, 11 settings: the share of members with and without the toggle test, the toggle
% shift in percentage points (Table S2), and the correlation of each share with success.
    tags = {'graded_separate', 'graded_contrast', 'saturating_separate', 'saturating_contrast', ...
            'wellmixed', 'ring_k1', 'ring_k2', 'ring_k5', 'ring_k10', 'fission', 'fission_sham'};
    S = load(fullfile(pub, 'gen500_c1_c2_split.mat'), 'per_replicate');
    G = load(fullfile(pub, 'group_two_level', 'group_fission_analysis_N1000.mat'));
    O = load(fullfile(pub, 'share_of_members_checks_11settings.mat'));
    storedSucc = [arrayfun(@(r) sum(r.succ), S.per_replicate(1:9)), G.A.fission.k, G.A.fission_sham.k];
    p('=== GENERATION-500 SHARES: generation 500, 11 settings ===\n');
    p('%-20s %5s %5s %5s %6s %8s %8s %8s %6s %6s %7s %13s %13s\n', 'setting', 'n', 'mem', ...
      'paper', 'repOK', 'share %', 'toggle %', 'delta pp', 'fail', 'fail%', 'P/O*', 'inv partner', 'inv other');
    for s = 1:11
        R = load(fullfile(out, sprintf('toggle_gen500_%s.mat', strrep(tags{s}, 'fission_sham', 'random_split'))));
        perRep = accumarray(R.rep, double(R.is_css));
        if s <= 9
            P = S.per_replicate(s);
            stored = round(double(P.pVm(:)) .* double(P.nper(:)));
        else
            arm = {'fission', 'fission_sham'}; stored = double(G.A.(arm{s - 9}).occ.nVm(:));
        end
        repOK = isequal(perRep(:), stored(:));
        V.label{s} = R.label; V.n(s) = R.n; V.mem(s) = R.nMem; V.fail(s) = R.nFail;
        V.occ(s) = R.nMem / R.n; V.occT(s) = (R.nMem - R.nFail) / R.n;
        V.ok(s) = R.nMem == R.pub_nvm && repOK && round(100 * V.occ(s), 1) == R.pub_occ_printed;
        V.succ(s) = 100 * mean(R.succ); V.succOK(s) = sum(R.succ) == storedSucc(s);
        V.pf(s) = R.nPartnerFail; V.of(s) = R.nOtherOnlyFail;
        V.inv(s, :) = [R.invPartner, R.scoredPartner, R.invOther, R.scoredOther];
        p('%-20s %5d %5d %5d %6d %8.2f %8.2f %+8.2f %6d %6.2f %3d/%-3d %5d/%-7d %5d/%-7d\n', ...
          R.label, R.n, R.nMem, R.pub_nvm, repOK, 100 * V.occ(s), 100 * V.occT(s), ...
          100 * (V.occT(s) - V.occ(s)), R.nFail, 100 * R.nFail / max(R.nMem, 1), ...
          R.nPartnerFail, R.nOtherOnlyFail, V.inv(s, :));
    end
    p('(repOK: per-replicate member counts equal the stored ones; P/O*: failing members with\n');
    p(' at least one invading partner-channel toggle / with invading toggles only among the other twelve;\n');
    p(' inv: invading toggles / toggles scored, partner channel M(1:2,3:4) and the other twelve)\n');
    pf = sum(V.pf); of = sum(V.of); iv = sum(V.inv, 1);
    p('POOLED 11 settings: %d of %d members fail (%.2f%%); failing members partner %d / other-only %d;\n', ...
      sum(V.fail), sum(V.mem), 100 * sum(V.fail) / sum(V.mem), pf, of);
    p('  invading toggles partner %d/%d (%.3f%%), other %d/%d (%.3f%%)\n', iv(1), iv(2), ...
      100 * iv(1) / iv(2), iv(3), iv(4), 100 * iv(3) / iv(4));
    V.r = corr(V.occ(:), V.succ(:)); V.rT = corr(V.occT(:), V.succ(:));
    V.rOK = abs(V.r - O.out.new.r_occ) < 1e-12 && all(V.succOK);
    p('CONTROL member counts (total, per replicate, printed digit): %s\n', pass(all(V.ok)));
    p('CONTROL success counts equal the stored ones (%s): %s\n', strjoin(arrayfun(@(k) sprintf('%d', k), storedSucc, 'UniformOutput', false), ','), pass(all(V.succOK)));
    p('CONTROL r(share of members, success) over 11 settings: here %+.6f, stored %+.6f: %s\n', ...
      V.r, O.out.new.r_occ, pass(V.rOK));
    p('r with toggle-inclusive share of members: %+.6f (delta %+.6f)\n', V.rT, V.rT - V.r);
    sig = 1:4;
    p('Signaling, gen 500: the paper''s %.1f-%.1f%%, toggle-inclusive %.1f-%.1f%%\n\n', ...
      100 * min(V.occ(sig)), 100 * max(V.occ(sig)), 100 * min(V.occT(sig)), 100 * max(V.occT(sig)));
end


% =========================================================================
function V = exp1_gen1(out, p)
% Generation 1, 10,000 random wirings per architecture: the same comparison.
    L = load(fullfile(out, 'gen1_toggle_silent.mat'));
    p('=== GENERATION-1 SHARES: generation 1, 10,000 random wirings per architecture ===\n');
    p('%-20s %5s %6s %8s %8s %8s %6s %13s %13s\n', 'architecture', 'mem', 'fail', 'share %', ...
      'toggle %', 'delta pp', 'P/O*', 'inv partner', 'inv other');
    for m = 1:4
        g = L.G(m);
        f = g.is_css & ~g.toggle_ok; c = g.toggle_cls;
        V.name{m} = g.name; V.occ(m) = sum(g.is_css) / g.n; V.occT(m) = sum(g.is_css & g.toggle_ok) / g.n;
        V.pf(m) = sum(f & c(:, 1) > 0); V.of(m) = sum(f & c(:, 1) == 0);
        V.inv(m, :) = [sum(c(g.is_css, 1)), 4 * sum(g.is_css), sum(c(g.is_css, 2)), 12 * sum(g.is_css)];
        p('%-20s %5d %6d %8.2f %8.2f %+8.3f %3d/%-3d %5d/%-7d %5d/%-7d\n', g.name, sum(g.is_css), ...
          sum(f), 100 * V.occ(m), 100 * V.occT(m), 100 * (V.occT(m) - V.occ(m)), V.pf(m), V.of(m), V.inv(m, :));
    end
    p('(controls: scope_checks_gen1 prints whether the C1 and member counts and the member stack reproduce)\n');
    p('Gen 1: the paper''s %.2f-%.2f%%, toggle-inclusive %.2f-%.2f%%\n\n', 100 * min(V.occ), ...
      100 * max(V.occ), 100 * min(V.occT), 100 * max(V.occT));
end


% =========================================================================
function exp1_shifts(V, V1, p)
% The largest toggle shifts: generation 500 (signaling, all 11 settings), generation 1, and r.
    d500 = abs(V.occT(1:4) - V.occ(1:4)) * 100;
    d1 = abs(V1.occT - V1.occ) * 100;
    dAll = abs(V.occT - V.occ) * 100;
    p('Toggle shifts: max |delta| gen 500 signaling %.2f pp, gen 1 %.3f pp,\n', max(d500), max(d1));
    p('  all 11 settings %.2f pp, |delta r| %.4f\n\n', max(dAll), abs(V.rT - V.r));
end


% =========================================================================
function exp2(pub, out, p)
% Generation-1 (C1) share with flagged clone states set aside (SI S2.3, "Most random wirings that
% cooperate with their clone do not retaliate"). filt: wirings that satisfy (C1) and are not
% flagged, over all 10,000; sec: the same count over the 10,000 less every flagged wiring; flagPct:
% the flagged share of all wirings; memAct: members among the unflagged wirings that satisfy (C1).
    L = load(fullfile(out, 'gen1_toggle_silent.mat'));
    C = load(fullfile(pub, 'css_c1_c2_split.mat'), 'c1_gen1');
    storedC1 = 100 * C.c1_gen1(:)';
    p('=== C1 SHARES WITHOUT FLAGGED CLONE STATES: cooperation condition (C1) at generation 1, silent / unconverged clones removed ===\n');
    p('%-20s %6s %7s %6s %6s %6s %6s %6s %8s %8s %8s %9s %9s\n', 'architecture', 'C1', 'C1 %', 'SIL', ...
      'UNC', 'both', 'SILonl', 'UNConl', 'filt %', 'delta', 'secnd %', 'members %', 'mem filt');
    for m = 1:4
        g = L.G(m); F = g.F; c1 = g.is_weak;
        sil = c1 & F.silent; unc = c1 & F.unconv; fl = sil | unc;
        filt(m) = 100 * sum(c1 & ~fl) / g.n; %#ok<AGROW>
        flagAll = F.silent | F.unconv;
        sec(m) = 100 * sum(c1 & ~fl) / (g.n - sum(flagAll)); %#ok<AGROW>
        pct_members = 100 * sum(g.is_css) / g.n; pct_members_unflagged = 100 * sum(g.is_css & ~fl) / g.n;
        p('%-20s %6d %7.2f %6d %6d %6d %6d %6d %8.2f %+8.2f %8.2f %9.2f %9.2f\n', g.name, sum(c1), ...
          100 * sum(c1) / g.n, sum(sil), sum(unc), sum(sil & unc), sum(sil & ~unc), sum(unc & ~sil), ...
          filt(m), filt(m) - 100 * sum(c1) / g.n, sec(m), pct_members, pct_members_unflagged);
        assert(abs(100 * sum(c1) / g.n - storedC1(m)) < 1e-9, 'C1 control');
        nonC1flag(m) = sum(~c1 & flagAll); %#ok<AGROW>
        flagPct(m) = 100 * sum(flagAll) / g.n; %#ok<AGROW>
        memAct(m) = 100 * sum(g.is_css & ~fl) / sum(c1 & ~fl); %#ok<AGROW>
        lo = F.outmax(c1);
        p('    C1 passers: min max(x_C,x_D) %.2g; passers with both outputs < 1e-20: %d; < 1e-6: %d; non-passers flagged %d\n', ...
          min(lo), sum(lo < 1e-20), sum(lo < 1e-6), nonC1flag(m));
    end
    p('(SIL = max(x_C,x_D) < 1e-3; UNC = 20,000-step re-run moves > 5%% or flips the readout;\n');
    p(' filt %% = passers neither SIL nor UNC over all 10,000 (read below); secnd %% = same numerator over the\n');
    p(' 10,000 less every flagged wiring, passers or not; mem filt = members neither SIL nor UNC)\n');
    p('CONTROL C1 shares %.2f / %.2f / %.2f / %.2f %% equal the stored ones (css_c1_c2_split.mat): PASS\n', storedC1);
    dev = abs(filt - storedC1); span = max(filt) - min(filt); spanS = max(sec) - min(sec);
    p('C1 shares: the paper''s 42.1-44.5%%; filtered, over all 10,000: %.1f-%.1f%%, max |shift| %.2f pts\n', ...
      min(filt), max(filt), max(dev));
    p('  span of the four filtered shares %.2f pts\n', span);
    p('  filtered, over the 10,000 less every flagged wiring: %.1f-%.1f%%, span %.2f pts\n', min(sec), max(sec), spanS);
    p('  flagged (SIL or UNC, passers or not) over all 10,000: %.2f / %.2f / %.2f / %.2f %% (%.1f-%.1f%%)\n', ...
      flagPct, min(flagPct), max(flagPct));
    p('  members among unflagged C1 passers: %.2f / %.2f / %.2f / %.2f %% (so %.1f-%.1f%% fail retaliation)\n', ...
      memAct, 100 - max(memAct), 100 - min(memAct));
end


